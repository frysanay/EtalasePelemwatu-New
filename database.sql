-- Database EtalasePelemwatu
-- PostgreSQL

-- Tabel kategori
CREATE TABLE IF NOT EXISTS categories (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR NOT NULL,
    description TEXT
);

-- Tabel pengguna/admin
CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR NOT NULL,
    email VARCHAR NOT NULL,
    password VARCHAR NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Tabel potensi desa
CREATE TABLE IF NOT EXISTS potensi (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id INTEGER NOT NULL,
    name VARCHAR NOT NULL,
    owner_name VARCHAR NOT NULL,
    whatsapp VARCHAR NOT NULL,
    address TEXT NOT NULL,
    description TEXT NOT NULL,
    location TEXT,
    status VARCHAR NOT NULL,
    reviewed_by INTEGER,
    reviewed_at TIMESTAMP,
    rejection_reason TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_potensi_category
        FOREIGN KEY (category_id)
        REFERENCES categories(id),

    CONSTRAINT fk_potensi_user
        FOREIGN KEY (reviewed_by)
        REFERENCES users(id)
);

-- Tabel gambar potensi
CREATE TABLE IF NOT EXISTS potensi_images (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    potensi_id INTEGER NOT NULL,
    image_path TEXT NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_potensi_images
        FOREIGN KEY (potensi_id)
        REFERENCES potensi(id)
);

